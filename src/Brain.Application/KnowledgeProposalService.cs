using System.Text;
using System.Text.RegularExpressions;
using Brain.Domain;

namespace Brain.Application;

public sealed partial class KnowledgeProposalService(IKnowledgeVault vault, IKnowledgeProposalStore store, TimeProvider time,
    IMetadataDocumentProcessor? metadata = null)
{
    public async Task<KnowledgeProposalView> ProposeAsync(AgentContext actor, ProposeKnowledgeChangeRequest request, CancellationToken ct = default)
    {
        actor.Require(Permissions.KnowledgeRead); actor.Require(Permissions.KnowledgePropose);
        Validation.Require(Enum.IsDefined(request.Operation), "Unknown knowledge operation.");
        Validation.Require(request.Operation != KnowledgeOperation.MetadataEnrichment, "Metadata enrichment proposals are generated by the administrative scanner.");
        Validation.Text(request.Content, "Content", 32000); // Preserve intentional Markdown whitespace.
        var reason = Validation.Text(request.Reason, "Reason", 2000);
        Validation.Require(!request.Content.Contains('\0'), "Content cannot contain NUL characters.");
        try { new UTF8Encoding(false, true).GetByteCount(request.Content); }
        catch (EncoderFallbackException) { throw new BrainException(400, "Content must be valid Unicode."); }
        if (request.Operation == KnowledgeOperation.CreateDocument)
            Validation.Require(request.RevisionToken is null, "New documents require an absent revision token.");
        else Validation.Require(request.RevisionToken is not null && TokenPattern().IsMatch(request.RevisionToken), "A valid revision token is required.");
        Validation.Require(request.Operation == KnowledgeOperation.ReplaceSection ?
            !string.IsNullOrWhiteSpace(request.Section) && request.Section.Length <= 4000 : request.Section is null,
            "Only replace_section accepts a required section heading hierarchy.");
        var before = await TryReadAsync(request.Path, ct);
        _ = KnowledgeChangePlanner.Plan(request.Operation, request.Content, request.Section, before, request.RevisionToken);
        var proposal = new KnowledgeWriteProposal
        {
            AgentId = actor.Id, Path = request.Path, Operation = request.Operation, Content = request.Content,
            RevisionToken = request.RevisionToken, Section = request.Section, Reason = reason,
            Status = KnowledgeProposalStatus.Pending, CreatedAt = time.GetUtcNow(), UpdatedAt = time.GetUtcNow()
        };
        await store.CreateAsync(proposal, Event(actor.Id, "brain.knowledge.proposed", proposal.Id), ct);
        return KnowledgeProposalView.From(proposal);
    }

    public async Task<KnowledgeProposalView> GetAsync(AgentContext actor, Guid id, CancellationToken ct = default) =>
        KnowledgeProposalView.From(await VisibleAsync(actor, id, ct));

    public async Task<IReadOnlyList<KnowledgeProposalView>> ListAsync(AgentContext actor, KnowledgeProposalStatus? status, int limit, CancellationToken ct = default, string? type = null)
    {
        actor.Require(Permissions.KnowledgeRead);
        Validation.Require(limit is >= 1 and <= 100, "Limit must be between 1 and 100.");
        Validation.Require(status is null || Enum.IsDefined(status.Value), "Unknown proposal status.");
        Validation.Require(type is null or "metadata_enrichment" or "knowledge_change", "Unknown proposal type.");
        return (await store.ListAsync(actor.Has(Permissions.KnowledgeAdmin) ? null : actor.Id, status, limit, ct,
                type is null ? null : type == "metadata_enrichment"))
            .Select(KnowledgeProposalView.From).ToArray();
    }

    public async Task<KnowledgeProposalPreview> PreviewAsync(AgentContext actor, Guid id, CancellationToken ct = default)
    {
        var proposal = await VisibleAsync(actor, id, ct);
        var before = await TryReadAsync(proposal.Path, ct);
        try
        {
            return new(proposal.Path, before?.RevisionToken, before?.Content,
                KnowledgeChangePlanner.Plan(proposal.Operation, proposal.Content, proposal.Section, before, proposal.RevisionToken, metadata), true, null);
        }
        catch (BrainException e) when (e.StatusCode is 400 or 409)
        { return new(proposal.Path, before?.RevisionToken, before?.Content, null, false, e.Message); }
    }

    public async Task<KnowledgeProposalView> ReviewAsync(AgentContext actor, Guid id, ReviewKnowledgeProposalRequest request, bool approve, CancellationToken ct = default)
    {
        actor.Require(Permissions.KnowledgeRead); actor.Require(Permissions.KnowledgeAdmin);
        var proposal = await VisibleAsync(actor, id, ct);
        if (proposal.Status != KnowledgeProposalStatus.Pending || proposal.Version != request.Version)
            throw new BrainException(409, "The proposal has already changed or been reviewed.");
        proposal.ReviewReason = Validation.Text(request.Reason, "Review reason", 2000);
        proposal.ReviewerId = actor.Id; proposal.ReviewedAt = time.GetUtcNow(); proposal.UpdatedAt = time.GetUtcNow();
        proposal.Status = approve ? KnowledgeProposalStatus.Approved : KnowledgeProposalStatus.Rejected;
        await store.SaveAsync(proposal, Event(actor.Id, proposal.Operation == KnowledgeOperation.MetadataEnrichment
            ? (approve ? "brain.metadata.proposal.approved" : "brain.metadata.proposal.rejected")
            : (approve ? "brain.knowledge.approved" : "brain.knowledge.rejected"), id), ct);
        return KnowledgeProposalView.From(proposal);
    }

    internal async Task<KnowledgeWriteProposal> BuildMetadataAsync(AgentContext actor, VaultDocument source, MetadataPatch patch,
        MetadataProviderInfo provider, double? confidence, CancellationToken ct)
    {
        actor.Require(Permissions.KnowledgeRead); actor.Require(Permissions.KnowledgePropose);
        var content = System.Text.Json.JsonSerializer.Serialize(patch, MetadataJson.Options);
        Validation.Text(content, "Metadata patch", 32000);
        var before = await vault.ReadAsync(source.Path, ct);
        _ = KnowledgeChangePlanner.Plan(KnowledgeOperation.MetadataEnrichment, content, null, before, source.RevisionToken, metadata);
        return new KnowledgeWriteProposal
        {
            AgentId = actor.Id, Path = source.Path, Operation = KnowledgeOperation.MetadataEnrichment, Content = content,
            RevisionToken = source.RevisionToken, Reason = "Enrich missing, invalid, stale or outdated frontmatter metadata; preserve valid human fields.",
            Status = KnowledgeProposalStatus.Pending, CreatedAt = time.GetUtcNow(), UpdatedAt = time.GetUtcNow(),
            MetadataSchemaVersion = patch.SchemaVersion, EnrichmentProvider = provider.Provider, EnrichmentModel = provider.Model,
            EnrichmentConfidence = confidence, GeneratedBy = "metadata-enrichment-worker"
        };
    }

    private async Task<KnowledgeWriteProposal> VisibleAsync(AgentContext actor, Guid id, CancellationToken ct)
    {
        actor.Require(Permissions.KnowledgeRead);
        var proposal = await store.FindAsync(id, ct);
        if (proposal is null || (proposal.AgentId != actor.Id && !actor.Has(Permissions.KnowledgeAdmin)))
            throw new BrainException(404, "Proposal not found.");
        return proposal;
    }
    private async Task<VaultDocument?> TryReadAsync(string path, CancellationToken ct)
    {
        try { return await vault.ReadAsync(path, ct); }
        catch (BrainException e) when (e.StatusCode == 404) { return null; }
    }
    private AuditEvent Event(string actor, string action, Guid id) => new()
    { AgentId = actor, Action = action, Resource = id.ToString(), Timestamp = time.GetUtcNow() };
    [GeneratedRegex(@"\Av1\.[a-f0-9]{64}\z")]
    private static partial Regex TokenPattern();
}
