using System.Diagnostics;
using System.Text;

namespace Brain.Tests;

internal sealed class VaultSandbox : IDisposable
{
    private readonly List<string> links = [];
    public string Root { get; } = Path.Combine(Path.GetTempPath(), "brain-vault-" + Guid.NewGuid().ToString("N"));
    public VaultSandbox() => Directory.CreateDirectory(Root);
    public string Write(string path, string content)
    {
        var full = Path.Combine(Root, path);
        Directory.CreateDirectory(Path.GetDirectoryName(full)!);
        File.WriteAllText(full, content, new UTF8Encoding(false));
        return full;
    }
    public void LinkDirectory(string name, string target)
    {
        var link = Path.Combine(Root, name);
        if (!OperatingSystem.IsWindows()) { Directory.CreateSymbolicLink(link, target); links.Add(link); return; }
        // Junctions exercise Windows reparse-point protection without requiring symlink privileges.
        var info = new ProcessStartInfo("powershell.exe") { UseShellExecute = false, CreateNoWindow = true };
        info.ArgumentList.Add("-NoProfile"); info.ArgumentList.Add("-NonInteractive"); info.ArgumentList.Add("-Command");
        info.ArgumentList.Add("$ErrorActionPreference='Stop'; $null = New-Item -ItemType Junction -Path $env:BRAIN_TEST_LINK -Target $env:BRAIN_TEST_TARGET");
        info.Environment["BRAIN_TEST_LINK"] = link;
        info.Environment["BRAIN_TEST_TARGET"] = target;
        using var process = Process.Start(info)!;
        process.WaitForExit();
        if (process.ExitCode != 0) throw new InvalidOperationException("Could not create test junction.");
        links.Add(link);
    }
    public void Dispose()
    {
        foreach (var link in links) if (Directory.Exists(link)) Directory.Delete(link, false);
        if (Directory.Exists(Root)) TestGit.ClearReadOnly(Root);
        // The root and links are generated by this fixture; link targets are never removed here.
        if (Directory.Exists(Root)) Directory.Delete(Root, true);
    }
}
